#[test]
fn math_computes_as_v8_does() {
    for (x, want) in NODE {
        let got = [
            math::sin(x),
            math::cos(x),
            math::tan(x),
            math::exp(x % 10.0),
            math::log(x),
            math::atan(x),
            math::atan2(x, 0.7),
            math::asin(1.0 / (1.0 + x)),
            math::acos(1.0 / (1.0 + x)),
        ];
        assert_eq!(got, want, "{x}");
    }
}

#[test]
fn math_keeps_javascripts_edges() {
    assert!(math::sin(f64::INFINITY).is_nan());
    assert!(math::log(-1.0).is_nan());
    assert_eq!(math::log(0.0), f64::NEG_INFINITY);
    assert_eq!(math::exp(1.0), std::f64::consts::E);
    assert_eq!(math::exp(f64::NEG_INFINITY), 0.0);
    assert!(math::asin(2.0).is_nan());
    assert_eq!(math::atan2(0.0, -1.0), std::f64::consts::PI);
}
